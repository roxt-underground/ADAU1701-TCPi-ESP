#pragma once

#include <Arduino.h>

/**
 * @brief Сериализует строку из шестнадцатерных байтов в массив.
 *
 * Входная строка состоит из значений, разделённых запятыми, каждое из
 * которых представляет один байт в HEX-формате (0x00–0xFF), например:
 * "a8,c6,0,12".
 *
 * Результат записывается в массив output следующим образом:
 *   - output[0]   — количество сериализованных байтов;
 *   - output[1..n] — сами значения байтов.
 *
 * Пример: "a8,c6,0,12" -> {0x04, 0xA8, 0xC6, 0x00, 0x12}.
 *
 * @param[in]  input  Строка с HEX-значениями, разделёнными запятыми.
 * @param[out] output Выходной массив для сериализованных данных.
 * @param[in]  maxLen Максимальный размер массива output
 *                    (должен быть >= количество байтов + 1).
 *
 * @return true при успешной сериализации, false при ошибке
 *         (неверный формат, выход за границы диапазона,
 *          нехватка места в массиве, null-указатель или исключение).
 *
 * @note Все исключения перехватываются внутри функции,
 *       поэтому вызывающему коду достаточно проверять возвращаемое значение.
 */
bool serializeBytes(const String input, uint8_t* output, size_t maxLen);
